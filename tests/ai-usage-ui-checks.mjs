import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html = fs.readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const source = html.slice(html.indexOf('    var aiUsageRequest ='), html.indexOf('    function automationRules()'));
const elements = Object.fromEntries(['ai-cost-panel', 'ai-popup-usage', 'ai-page-usage'].map(id => [id, { textContent: '' }]));
const sandbox = { document: { getElementById: id => elements[id] }, window: {}, wsActiveId: 'a', currentLang: 'fr', setTimeout, clearTimeout, applyStaticCopyTranslations() {} };
vm.createContext(sandbox);
vm.runInContext(source, sandbox);
await sandbox.loadAiUsagePanel();
assert.match(elements['ai-cost-panel'].textContent, /hors connexion/);
assert.equal(elements['ai-cost-panel'].textContent, elements['ai-page-usage'].textContent);
sandbox.window.profactureAiUsage = async () => { throw Object.assign(new Error('auth'), { code: 'unauthenticated' }); };
await sandbox.loadAiUsagePanel();
assert.match(elements['ai-page-usage'].textContent, /Connectez-vous/);
sandbox.currentLang = 'en-US';
sandbox.window.profactureAiUsage = async () => { throw new Error('network'); };
await sandbox.loadAiUsagePanel();
assert.match(elements['ai-page-usage'].textContent, /unavailable/);
let resolve;
sandbox.window.profactureAiUsage = () => new Promise(r => { resolve = r; });
const pending = sandbox.loadAiUsagePanel();
sandbox.wsActiveId = 'b';
elements['ai-page-usage'].textContent = 'Company B';
resolve({ dailyUsed: 1, dailyLimit: 10 });
await pending;
assert.equal(elements['ai-page-usage'].textContent, 'Company B');
console.log('AI usage UI checks passed: offline, auth, network and stale company response.');
